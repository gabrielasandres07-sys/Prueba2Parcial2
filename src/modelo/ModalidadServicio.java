public enum ModalidadServicio {
    EN_ESTABLECIMIENTO("Consumo en el establecimiento"),
    A_DOMICILIO("Pedido a domicilio");

    private final String descripcion;

    ModalidadServicio(String descripcion) {
        this.descripcion = descripcion;
    }

    public String getDescripcion() {
        return descripcion;
    }

    @Override
    public String toString() {
        return descripcion;
    }
}
